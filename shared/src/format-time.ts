/**
 * format-time.ts — shared relative-time formatting for desktop + mobile.
 *
 * Renders "time ago" strings (just now / Nm / Nh / Nd, then an absolute date past
 * a week). For absolute date+time formatting on desktop see `src/lib/format-date`.
 */

/** Format an ISO date string as a human-readable relative time (e.g. "5m ago"). */
export function formatTimeAgo(dateStr: string): string {
  const date = new Date(dateStr);
  const now = new Date();
  const diffMs = now.getTime() - date.getTime();
  const diffMins = Math.floor(diffMs / 60000);
  const diffHours = Math.floor(diffMs / 3600000);
  const diffDays = Math.floor(diffMs / 86400000);

  if (diffMins < 1) return "just now";
  if (diffMins < 60) return `${diffMins}m ago`;
  if (diffHours < 24) return `${diffHours}h ago`;
  if (diffDays < 7) return `${diffDays}d ago`;
  return date.toLocaleDateString();
}
